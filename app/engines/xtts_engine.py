from __future__ import annotations

import importlib.util
import os
from collections.abc import Callable
from pathlib import Path
from typing import Any

try:
    import numpy as np
except ImportError:  # pragma: no cover - numpy is a hard requirement in practice
    np = None  # type: ignore[assignment]

from app.core.config import config_manager
from app.core.device import device_manager
from app.core.logging_setup import get_logger
from app.engines.base import EngineLicense, SynthesisParameters, TTSEngine
from app.engines.chatterbox_engine import PerthWatermark

logger = get_logger("xtts")


class XTTSEngine(TTSEngine):
    """Adapter for Coqui XTTS v2 zero-shot multi-lingual cloning."""

    def __init__(self) -> None:
        self._is_loaded = False
        self._model: Any = None
        self._device = "cpu"

    @property
    def _weights_dir(self) -> Path:
        return config_manager.get_models_directory() / "xtts_v2"

    @property
    def name(self) -> str:
        return "XTTS v2 (Coqui)"

    @property
    def license_info(self) -> EngineLicense:
        return EngineLicense(
            name="Coqui Public Model License (CPML)",
            url="https://coqui.ai/cpml",
            commercial_permitted=False,
            notice=(
                "NON-COMMERCIAL LICENSE WARNING: XTTS v2 is released under the CPML license. "
                "You may NOT use this engine or any speech generated by it for commercial purposes, "
                "monetization, advertising, or enterprise services without a commercial license."
            ),
        )

    @property
    def supported_languages(self) -> list[str]:
        return ["en", "es", "fr", "de", "it", "pt", "pl", "tr", "ru", "nl", "cs", "ar", "zh", "ja", "ko", "hu", "hi"]

    @property
    def requires_gpu_recommended(self) -> bool:
        return True  # XTTS v2 autoregressive model benefits heavily from CUDA / MPS

    @property
    def native_sample_rate(self) -> int:
        return 24000

    def is_available(self) -> bool:
        """True only when the Coqui TTS runtime is importable."""
        return importlib.util.find_spec("TTS") is not None

    def is_loaded(self) -> bool:
        return self._is_loaded

    def get_default_params(self) -> SynthesisParameters:
        return SynthesisParameters(
            temperature=0.75,
            cfg_weight=2.0,
            exaggeration=1.0,
            speed=1.0,
            seed=-1,
            top_p=0.85,
            repetition_penalty=2.0,
            language="en",
            enable_watermark=True,
        )

    def load_model(self, progress_callback: Callable[[float, str], None] | None = None) -> bool:
        if self._is_loaded:
            return True

        self._device = device_manager.get_preferred_device(config_manager.config.device_preference)
        logger.info("Loading XTTS v2 on device %s", self._device)

        if progress_callback:
            progress_callback(15.0, f"Initializing XTTS v2 weights on {self._device.upper()}")

        try:
            # Check for Coqui TTS library
            try:
                from TTS.api import TTS  # type: ignore
                if progress_callback:
                    progress_callback(60.0, "Loading XTTS model into memory")
                self._model = TTS("tts_models/multilingual/multi-dataset/xtts_v2", gpu=(self._device == "cuda"))
                logger.info("Successfully loaded official Coqui XTTS v2 pipeline.")
            except ImportError:
                logger.error(
                    "The Coqui TTS package is not installed. "
                    "Install it with: pip install coqui-tts"
                )
                self._is_loaded = False
                return False

            if progress_callback:
                progress_callback(100.0, "XTTS v2 model ready.")

            self._is_loaded = True
            return True
        except Exception as e:
            logger.error("Failed to load XTTS v2 model: %s", e)
            self._is_loaded = False
            return False

    def unload_model(self) -> None:
        logger.info("Unloading XTTS v2.")
        self._model = None
        self._is_loaded = False
        device_manager.clear_cache()

    def clone_and_synthesize(
        self,
        text: str,
        reference_audio_path: str | Path,
        params: SynthesisParameters,
    ) -> tuple[np.ndarray, int]:
        if not self._is_loaded:
            self.load_model()

        if not text.strip():
            return np.zeros(0, dtype=np.float32), self.native_sample_rate

        # If Coqui TTS library is loaded
        if hasattr(self._model, "tts_to_file"):
            import tempfile
            tmp_out = None
            try:
                import soundfile as sf
                with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
                    tmp_out = tmp.name

                self._model.tts_to_file(
                    text=text,
                    speaker_wav=str(reference_audio_path),
                    language="zh-cn" if params.language == "zh" else params.language,  # XTTS naming
                    file_path=tmp_out,
                    speed=params.speed,
                    temperature=params.temperature,
                )
                data, sr = sf.read(tmp_out, dtype="float32")
                if params.enable_watermark:
                    data = PerthWatermark.apply(data, sr)
                return data, sr
            except Exception as e:
                logger.error("Coqui native synthesis failed: %s", e)
                raise RuntimeError(f"XTTS synthesis failed: {e}") from e
            finally:
                if tmp_out:
                    try:
                        os.remove(tmp_out)
                    except OSError:
                        pass

        raise RuntimeError(
            "XTTS v2 is not available. Install the Coqui runtime with `pip install coqui-tts`."
        )

    def synthesize_chunk(
        self,
        text: str,
        reference_audio_path: str | Path,
        params: SynthesisParameters,
    ) -> tuple[np.ndarray, int]:
        """Synthesize a single chunk for streaming playback."""
        return self.clone_and_synthesize(text, reference_audio_path, params)
